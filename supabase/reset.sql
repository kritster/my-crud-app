-- ---------------------------------------------------------------------
-- แบบ A: ล้างทั้งหมด รวมบัญชีผู้ใช้ (เริ่มใหม่หมด) — บัญชี admin ก็ถูกลบด้วย
--   หลังรัน: กด "ออกจากระบบ" หรือล้าง cookie ของเว็บ แล้วสมัครใหม่
--   สมัครด้วย krit@uru.ac.th จะได้ role admin ทันที (trigger ใน schema.sql)
--   ⚠️ ปิด Confirm email ไว้ ใครสมัครอีเมลนี้ก่อนจะได้ admin → ให้ admin สมัครทันทีหลัง reset
-- ---------------------------------------------------------------------
begin;

-- ลบบัญชีผู้ใช้ทั้งหมด → profiles และ items ของแต่ละคนถูกลบตาม (on delete cascade)
delete from auth.users;

-- ลบ items ที่เหลือ (แถวที่ user_id เป็น null) และให้ id เริ่มนับที่ 1 ใหม่
truncate table public.items, public.profiles restart identity;

commit;


-- ---------------------------------------------------------------------
-- แบบ B: ล้างเฉพาะรายการ เก็บบัญชีผู้ใช้ไว้
-- ---------------------------------------------------------------------
-- truncate table public.items restart identity;


-- ---------------------------------------------------------------------
-- ตรวจผล: แบบ A ต้องได้ 0, 0, 0, 0 / แบบ B ต้องได้ items = 0 (admins ยังอยู่)
-- ---------------------------------------------------------------------
select
  (select count(*) from auth.users)      as users,
  (select count(*) from public.profiles) as profiles,
  (select count(*) from public.items)    as items,
  (select count(*) from public.profiles where role = 'admin') as admins;
